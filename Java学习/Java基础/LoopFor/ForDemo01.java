package LoopFor;

public class ForDemo01 {
    public static void main(String[] args) {
        /*
        实现游戏中连续跳跃10次，用输出语句模拟跳跃的逻辑

        格式：
        for (初始化语句; 条件判断语句; 条件控制语句) {
            循环体
        }
        
        三要素：
        1. 初始化表达式：在循环开始前执行一次，用于初始化循环变量
        2. 条件判断语句：在每次循环前执行，用于判断是否继续循环
        3. 条件控制语句：在每次循环后执行，用于更新循环变量

        循环体：在每次循环中执行的代码块

        初始化语句 -> 条件判断语句 -> 循环体 -> 条件控制语句 -> 循环体
        */
       for (int i = 0; i < 10; i++) {
           System.out.println("跳跃" + (i + 1) + "次");
       }
    }
}
